"""TC-301..TC-320: EmployeeTable UI automation.

Drives the EmployeeTable widget through its public surface (and a few
white-box seams where a behavior has no public boundary) using the `gui`
fixture from conftest.py. All assertions are behaviour-oriented: they
describe what the table should render / return for a given input, never
how it is implemented internally.

Black-box seams used (and why):
  - tree.tag_configure(name, option)   : the only way to read a tag's
                                          configured style after the fact.
  - tree.get_children / tree.item      : the public introspection API of
                                          ttk.Treeview.
  - _on_tree_motion / _strip_hover_tag : private, but hover-row highlight
                                          has no public trigger — Motion
                                          events require pixel coordinates
                                          we cannot compute portably, so
                                          the private handler is the seam.
"""

